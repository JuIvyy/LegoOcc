_CLIP = {}


@torch.no_grad()
def encode_text(names, device='cuda'):
    """Prompt-ensembled CLIP ViT-B/16 (OpenAI) text features, (len(names), 512) float32.

    Matches how the default LegoOcc vocabulary was encoded at training time.
    """
    try:
        import open_clip
    except ImportError as e:
        raise ImportError('Custom vocabularies need CLIP: `pip install open_clip_torch`.') from e

    device = torch.device(device)
    if device not in _CLIP:
        model = open_clip.create_model('ViT-B-16', pretrained='openai', precision='fp16', device=device)
        _CLIP[device] = model.eval()
    clip = _CLIP[device]

    features = []
    for name in names:
        tokens = open_clip.tokenize([t(name) for t in openai_imagenet_template]).to(device)
        feature = clip.encode_text(tokens)
        feature /= feature.norm(dim=-1, keepdim=True)
        feature = feature.mean(dim=0)
        feature /= feature.norm()
        features.append(feature)
    return torch.stack(features).float()
